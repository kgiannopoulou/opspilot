"""Simulated incidents with known answers, for the investigation benchmark.

Every case is generated by the ShopStream simulator, so the ground truth is not a label someone typed in: it is the
fault that was injected. Cases vary the noise (seed), how long the fault has been running when the investigation
starts, which service the incident is declared on, whether a second fault overlaps, and include incidents where
nothing is wrong at all (the engine should say so, with low confidence).
"""

from __future__ import annotations

from dataclasses import dataclass, field

# Scenario injected by the simulator → hypothesis the engine should conclude, and the runbook it should retrieve.
EXPECTED = {
    "payment_gateway_timeout": ("payment_gateway_timeout", "payment-gateway-timeout"),
    "db_pool_exhaustion": ("db_connection_pool_exhaustion", "db-connection-pool-exhaustion"),
    "smtp_auth_failure": ("smtp_authentication_failure", "smtp-credential-rotation"),
}
SYMPTOM = {"payment_gateway_timeout": "payment-service", "db_pool_exhaustion": "order-service",
           "smtp_auth_failure": "auth-service"}  # fmt: skip
ROOT = {"payment_gateway_timeout": "payment-service", "db_pool_exhaustion": "postgres-primary",
        "smtp_auth_failure": "notification-service"}  # fmt: skip
TITLE = {"payment_gateway_timeout": "Payment checkout timeout", "db_pool_exhaustion": "Merchant dashboard slow",
         "smtp_auth_failure": "HTTP 500 on password reset"}  # fmt: skip


@dataclass(frozen=True)
class Fault:
    scenario: str
    offset_minutes: int = 0  # relative to the investigated incident's onset (negative = started earlier)


@dataclass(frozen=True)
class InvestigationCase:
    id: str
    group: str
    title: str
    declared_on: list[str]  # affected services as the incident commander declared them
    faults: list[Fault]  # what the simulator injects
    minutes_running: int  # how long after onset the investigation runs
    seed: int
    expected_hypothesis: str  # "unknown" when nothing is wrong
    expected_documents: list[str] = field(default_factory=list)


def build_cases() -> list[InvestigationCase]:
    cases: list[InvestigationCase] = []
    n = 0

    def add(**kwargs: object) -> None:
        nonlocal n
        n += 1
        cases.append(InvestigationCase(id=f"I{n:02d}", **kwargs))  # type: ignore[arg-type]

    # 1. Single fault, declared where customers feel it, at three stages of the outage and three noise seeds.
    for scenario, (hypothesis, doc) in EXPECTED.items():
        for minutes in (5, 15, 40):
            for seed in (1, 2, 3):
                add(group="single fault", title=TITLE[scenario], declared_on=[SYMPTOM[scenario]],
                    faults=[Fault(scenario)], minutes_running=minutes, seed=seed, expected_hypothesis=hypothesis,
                    expected_documents=[doc])  # fmt: skip

    # 2. Declared on the root-cause service instead of the symptom (the on-call engineer guessed right).
    for scenario in ("db_pool_exhaustion", "smtp_auth_failure"):
        for seed in (4, 5):
            hypothesis, doc = EXPECTED[scenario]
            add(group="declared on root cause", title=TITLE[scenario], declared_on=[ROOT[scenario]],
                faults=[Fault(scenario)], minutes_running=20, seed=seed, expected_hypothesis=hypothesis,
                expected_documents=[doc])  # fmt: skip

    # 3. Two faults at once: each incident must find its own cause, not the louder neighbour's.
    pairs = [("payment_gateway_timeout", "smtp_auth_failure"), ("db_pool_exhaustion", "smtp_auth_failure"),
             ("payment_gateway_timeout", "db_pool_exhaustion")]  # fmt: skip
    for a, b in pairs:
        for target, other in ((a, b), (b, a)):
            hypothesis, doc = EXPECTED[target]
            add(group="overlapping faults", title=TITLE[target], declared_on=[SYMPTOM[target]],
                faults=[Fault(target), Fault(other, offset_minutes=-10)], minutes_running=20, seed=6,
                expected_hypothesis=hypothesis, expected_documents=[doc])  # fmt: skip

    # 4. Nothing is wrong: a customer report during normal operation.
    for service in ("payment-service", "order-service", "auth-service", "notification-service"):
        add(group="no fault", title=f"Customer report about {service}", declared_on=[service], faults=[],
            minutes_running=20, seed=7, expected_hypothesis="unknown")  # fmt: skip
    return cases
